  /**
   * Schreibt Text in Frakturschrift auf das Raster.
   * @returns {number} Gesamtbreite in Pixeln
   */
  function writeText(g, text, x, y, color, shadow, spacing) {
    spacing = spacing == null ? -1 : spacing;      // leichte Unterschneidung
    var cx = x;
    for (var i = 0; i < text.length; i++) {
      var ch = text[i].toUpperCase();
      var pat = FONT[ch];
      // Leerzeichen und unbekannte Zeichen rücken nur vor
      if (!pat) { cx += 6; continue; }

      for (var row = 0; row < pat.length; row++) {
        for (var col = 0; col < pat[row].length; col++) {
          if (pat[row][col] !== '#') continue;
          if (shadow) {
            g.set(cx + col + 1, y + row + 1, shadow);
          }
        }
      }
      for (var r2 = 0; r2 < pat.length; r2++) {
        for (var c2 = 0; c2 < pat[r2].length; c2++) {
          if (pat[r2][c2] !== '#') continue;
          g.set(cx + c2, y + r2, color);
        }
      }
      cx += GLYPH_W + spacing;
    }
    return cx - x;
  }

  /** Breite eines Textes vorab bestimmen, um ihn mittig zu setzen. */
  function textWidth(text, spacing) {
    spacing = spacing == null ? -1 : spacing;
    var w = 0;
    for (var i = 0; i < text.length; i++) {
      w += FONT[text[i].toUpperCase()] ? GLYPH_W + spacing : 6;
    }
    return w;
  }

  /* =======================================================
     Bausteine der Titelszene
     ======================================================= */

  function skyGradient(g) {
    var bands = [
      { to: 16, c: '#161a3e' },
      { to: 26, c: '#222a5a' },
      { to: 36, c: '#33407a' },
      { to: 46, c: '#4a5a96' },
      { to: 54, c: '#6b74a8' },
      { to: 60, c: '#8f7fa8' }
    ];
    var y = 0;
    bands.forEach(function (b) {
      for (; y < b.to; y++) for (var x = 0; x < W; x++) g.set(x, y, b.c);
    });
    // Weiche Übergänge
    bands.forEach(function (b, i) {
      if (i === 0) return;
      for (var x = 0; x < W; x++) {
        if ((x + b.to) % 2 === 0) g.set(x, b.to - 1, bands[i - 1].c);
      }
    });
  }

  function starsAndMoon(g, rnd) {
    for (var i = 0; i < 55; i++) {
      var x = Math.floor(rnd() * W), y = Math.floor(rnd() * 40);
      g.set(x, y, rnd() < 0.3 ? '#ffffff' : '#b9c6ee');
    }
    g.ellipse(172, 18, 7, 7, '#f2eecf');
    g.ellipse(175, 15, 6, 6, '#222a5a');       // Sichel
  }

  /** Ferne Bergkette als Tiefenebene. */
  function ridges(g) {
    for (var x = 0; x < W; x++) {
      var h = Math.abs(Math.sin(x / 23)) * 13 + Math.abs(Math.sin(x / 9)) * 5;
      for (var y = Math.round(60 - h); y < 62; y++) g.set(x, y, '#2b3358');
    }
    for (var x2 = 0; x2 < W; x2++) {
      var h2 = Math.abs(Math.sin(x2 / 17 + 2)) * 8 + 3;
      for (var y2 = Math.round(62 - h2); y2 < 64; y2++) g.set(x2, y2, '#39406b');
    }
  }

  function meadow(g, rnd) {
    for (var y = 62; y < H; y++) {
      var t = (y - 62) / (H - 62);
      for (var x = 0; x < W; x++) {
        var c = t < 0.25 ? '#2c5233' : (t < 0.6 ? '#356140' : '#28492f');
        if ((x * 5 + y * 3) % 19 === 0) c = '#24422b';
        g.set(x, y, c);
      }
    }
  }

  /** Der Weg, den die Gegner nehmen – das Erkennungszeichen des Genres. */
  function path(g) {
    var pts = [];
    for (var x = 0; x < W; x++) {
      var y = 84 + Math.round(Math.sin(x / 26) * 7);
      pts.push(y);
      for (var k = -6; k <= 6; k++) {
        g.set(x, y + k, Math.abs(k) > 5 ? '#5b4830' : '#8a6f4a');
      }
      // Kiesel
      if (x % 7 === 0) g.set(x, y + ((x / 7) % 5) - 2, '#a08a62');
    }
    return pts;
  }

  function castle(g, x, baseY) {
    g.rect(x - 13, baseY - 20, 26, 20, '#5f6779');
    g.rect(x - 11, baseY - 18, 22, 18, '#7a8296');
    for (var i = 0; i < 4; i++) {
      g.rect(x - 13 + i * 7, baseY - 24, 4, 4, '#7a8296');
    }
    [-1, 1].forEach(function (s) {
      var tx = x + s * 17;
      g.rect(tx - 4, baseY - 28, 8, 28, '#5f6779');
      g.rect(tx - 3, baseY - 26, 6, 26, '#7a8296');
      for (var k = 0; k < 5; k++) {
        g.rect(tx - 4 + k, baseY - 33 + k, Math.max(1, 8 - k * 2), 1, '#8a3a3a');
      }
    });
    g.rect(x - 3, baseY - 8, 6, 8, '#241a2b');
    g.rect(x - 8, baseY - 15, 3, 4, '#ffd98a');
    g.rect(x + 6, baseY - 15, 3, 4, '#ffd98a');
    // Banner
    g.rect(x, baseY - 34, 1, 7, '#5a4a3a');
    g.rect(x + 1, baseY - 34, 6, 4, '#3a5f9e');
  }

  /** Verteidigungsturm, der gerade feuert. */
  function tower(g, x, baseY, kind) {
    g.ellipse(x, baseY, 7, 3, '#3f3a2e');
    g.rect(x - 5, baseY - 9, 10, 9, '#6a7183');
    g.rect(x - 4, baseY - 8, 8, 8, '#8a91a3');
    for (var i = 0; i < 3; i++) g.rect(x - 5 + i * 4, baseY - 12, 3, 3, '#8a91a3');

    if (kind === 'bow') {                    // Bogenturm
      g.rect(x - 1, baseY - 18, 3, 6, '#5a4a3a');
      g.ellipse(x, baseY - 20, 3, 3, '#5ad1ff');
      g.rect(x + 3, baseY - 20, 5, 1, '#fff2c8');   // Pfeil
      g.rect(x + 8, baseY - 20, 2, 1, '#ffd166');
    } else {                                  // Katapult
      g.rect(x - 6, baseY - 15, 12, 3, '#6d4a2a');
      g.rect(x + 3, baseY - 19, 6, 2, '#6d4a2a');
      g.ellipse(x + 10, baseY - 22, 3, 3, '#8d93a6');
    }
  }

  /** Anrückende Gegner auf dem Weg. */
  function foes(g, pathY, rnd) {
    var xs = [24, 40, 58, 74, 92, 110, 128];
    xs.forEach(function (x, i) {
      var y = pathY[x] || 84;
      var s = 1 + (i % 3) * 0.15;
      var col = i % 3 === 0 ? '#8fbf5a' : (i % 3 === 1 ? '#c1533a' : '#9a8fb5');
      g.ellipse(x, y - 5 * s, 2.4 * s, 2.6 * s, '#161020');
      g.ellipse(x, y - 5 * s, 1.8 * s, 2 * s, col);
      g.rect(Math.round(x - 2 * s), Math.round(y - 3 * s), Math.round(4 * s), Math.round(4 * s), '#161020');
      g.rect(Math.round(x - 1.4 * s), Math.round(y - 2.4 * s), Math.round(2.8 * s), Math.round(3 * s), col);
      // Augen
      g.set(Math.round(x - 1), Math.round(y - 5 * s), '#ffffff');
      g.set(Math.round(x + 1), Math.round(y - 5 * s), '#ffffff');
      if (i % 2 === 0) g.rect(Math.round(x + 3 * s), Math.round(y - 11 * s), 1, Math.round(8 * s), '#3a2a1c');
    });
  }

  /** Geschossbahnen vom Turm zu den Gegnern. */
  function shots(g) {
    [[46, 68, 62, 79], [150, 66, 128, 80]].forEach(function (s) {
      var steps = 14;
      for (var i = 0; i < steps; i++) {
        var t = i / steps;
        var x = Math.round(U.lerp(s[0], s[2], t));
        var y = Math.round(U.lerp(s[1], s[3], t) - Math.sin(t * Math.PI) * 6);
        g.set(x, y, i > steps - 4 ? '#ffd166' : '#fff2c8');
      }
    });
  }

  /* =======================================================
     Titelbild bauen
     ======================================================= */
  function build(seed) {
    var g = new TD.PixelGrid(W);
    var rnd = U.rng(seed || 7);

    skyGradient(g);
    starsAndMoon(g, rnd);
    ridges(g);
    meadow(g, rnd);
    var pathY = path(g);

    castle(g, 168, 78);
    tower(g, 46, 74, 'bow');
    tower(g, 150, 72, 'cat');
    foes(g, pathY, rnd);
    shots(g);

    /* --- Hauptfiguren in einer Reihe --- */
    var order = TD.FACTION_ORDER;
    var slot = 46;
    var startX = Math.round((W - order.length * slot) / 2) + 7;
    order.forEach(function (fk, i) {
      var cg = TD.characters.grid(fk);
      var ox = startX + i * slot;
      var oy = H - 34;                       // Portraits ragen unten hinein
      // Podest
      g.ellipse(ox + 16, H - 3, 17, 4, '#1e3a24');
      for (var y = 0; y < 32; y++) {
        for (var x = 0; x < 32; x++) {
          var c = cg.get(x, y);
          if (!c) continue;
          if (oy + y >= H) continue;
          g.set(ox + x, oy + y, c);
        }
      }
    });

    /* --- Logo --- */
    var t1 = 'TOWER', t2 = 'DEFENSE';
    var w1 = textWidth(t1), w2 = textWidth(t2);
    writeText(g, t1, Math.round((W - w1) / 2), 6, '#f2d98a', '#3a2410');
    writeText(g, t2, Math.round((W - w2) / 2), 22, '#f2d98a', '#3a2410');

    // Zierlinien links und rechts der Jahreszahl
    var y26 = 38;
    var w3 = textWidth('2026');
    var x3 = Math.round((W - w3) / 2);
    writeText(g, '2026', x3, y26, '#c9a24a', '#3a2410');
    for (var lx = 14; lx < x3 - 8; lx++) {
      g.set(lx, y26 + 6, '#c9a24a');
      g.set(W - 1 - lx, y26 + 6, '#c9a24a');
    }
    [x3 - 7, W - x3 + 5].forEach(function (dx) {
      g.ellipse(dx, y26 + 6, 2, 2, '#f2d98a');
    });

    return g;
  }

  /* =======================================================
     Öffentliche Schnittstelle
     ======================================================= */
  var cache = null;

  TD.titlescreen = {
    WIDTH: W, HEIGHT: H,

    draw: function (canvas, scale) {
      scale = scale || 4;
      if (!cache) cache = build(7);
      var g = cache;

      var dpr = Math.min(global.devicePixelRatio || 1, 2);
      canvas.width = W * scale * dpr;
      canvas.height = H * scale * dpr;
      canvas.style.width = '100%';
      canvas.style.height = 'auto';

      var ctx = canvas.getContext('2d');
      ctx.scale(dpr, dpr);
      ctx.imageSmoothingEnabled = false;
      ctx.fillStyle = '#0a0e1a';
      ctx.fillRect(0, 0, W * scale, H * scale);

      for (var y = 0; y < H; y++) {
        for (var x = 0; x < W; x++) {
          var c = g.get(x, y);
          if (!c) continue;
          ctx.fillStyle = c;
          ctx.fillRect(x * scale, y * scale, scale, scale);
        }
      }
    },

    /** Frakturschrift auch anderweitig nutzbar (z. B. Siegesbanner). */
    writeText: writeText,
    textWidth: textWidth
  };
